const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { surface?: boolean }
>(({ className, surface, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-2xl border border-border shadow-2 bg-card text-card-foreground",
      surface && "bg-surface-elevated",
      className,
    )}
    {...props}
  />
))
Card.displayName = "Card"

